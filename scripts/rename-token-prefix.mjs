/*
 * One-shot rename onto the single `--helia-` package prefix.
 *
 * The design system used two prefixes: `--ds-*` for the shared primitives in
 * src/styles/tokens.css and `--hub-*` for the hub's semantic layer. Both are
 * now `--helia-`; the two layers stay in separate files but share the prefix.
 * The site-named class prefix `hub-` moves to `helia-` with them.
 *
 * This is committed rather than thrown away because aitg-handbook consumes
 * these tokens and has to run the identical rename over its own tree:
 *
 *   node scripts/rename-token-prefix.mjs --root <dir> --tokens-only
 *
 * `--tokens-only` skips the class rules. The `hub-` class prefix is the hub's
 * own; elsewhere `hub-` is as likely to mean the developer hub as a class
 * name, and the handbook's `.hub-pending` is exactly that.
 *
 * It is idempotent -- a second run reports zero replacements -- and it only
 * touches files git already tracks, so an untracked build output cannot be
 * rewritten.
 *
 * The shadcn `accent` rename is part of the same pass on purpose. The
 * package's react/ is generated by `shadcn add`, so a hand edit there is lost
 * on the next add; re-running this script over the regenerated files restores
 * it.
 *
 * Flags: --root <dir> (default: the package this script ships in),
 * --tokens-only, --dry-run.
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const tokensOnly = args.includes('--tokens-only');
const rootArg = args[args.indexOf('--root') + 1];
const ROOT = path.resolve(
  args.includes('--root') && rootArg
    ? rootArg
    : path.join(import.meta.dirname, '..'),
);

const EXTENSIONS = new Set([
  '.astro',
  '.css',
  '.js',
  '.json',
  '.md',
  '.mdx',
  '.mjs',
  '.ts',
  '.tsx',
]);

/*
 * Records of work already done quote the old names on purpose. Renaming inside
 * them would rewrite history rather than code.
 */
const SKIP_FILES = new Set([
  'docs/spike-shadcn.md',
  'docs/handoff.md',
  'package-lock.json',
  'scripts/rename-token-prefix.mjs',
  'packages/helia-ui/scripts/rename-token-prefix.mjs',
]);

/*
 * `hub-` also starts ordinary hyphenated English in prose and comments. These
 * are the tails that mean "of the hub", not a class name.
 */
const PROSE_TAILS = [
  'specific',
  'only',
  'named',
  'local',
  'authored',
  'owned',
  'side',
  'wide',
  'level',
  'first',
  'based',
  'scoped',
  'like',
  'style',
];

const TOKEN_RULES = [
  { name: 'primitive', pattern: /--ds-/g, replacement: '--helia-' },
  { name: 'semantic', pattern: /--hub-/g, replacement: '--helia-' },
];

const CLASS_RULES = [
  { name: 'data-attribute', pattern: /data-hub-/g, replacement: 'data-helia-' },
  {
    name: 'class',
    pattern: new RegExp(
      `(?<![-\\w])hub-(?=[a-z0-9])(?!(?:${PROSE_TAILS.join('|')})(?![\\w-]))`,
      'g',
    ),
    replacement: 'helia-',
  },
];

const RULES = tokensOnly ? TOKEN_RULES : [...TOKEN_RULES, ...CLASS_RULES];

/*
 * shadcn calls its hover surface `accent`, which collides with the brand
 * accent over `--color-accent`: shadcn.css is imported last, so its key won
 * and `bg-accent` meant "hover gray". Renaming shadcn's pair to `subtle`
 * leaves `accent` meaning the brand accent everywhere.
 *
 * Scoped to the generated components: src/styles/shadcn.css is hand-authored,
 * was renamed once, and discusses the old names in its comments, so a rerun
 * must leave it alone. The lookbehinds spare `--sl-color-accent` (Starlight's
 * own accent), `--sidebar-accent` (namespaced, so no collision) and the
 * `--helia-accent-*` card palette.
 *
 * The generated directory is found rather than named, so the rule holds
 * whether the root is a workspace holding the package or the package itself.
 */
const REACT_DIR = fs.existsSync(path.join(ROOT, 'packages/helia-ui/react'))
  ? 'packages/helia-ui/react/'
  : 'react/';

const ACCENT_RULE = {
  name: 'shadcn-accent',
  files: (rel) => rel.startsWith(REACT_DIR) && rel.endsWith('.tsx'),
  pattern: /(?<!sidebar)(?<!helia)(?<!sl-color)-accent\b/g,
  replacement: '-subtle',
};

/*
 * The shadcn/Astro alignment, in the same reapply-after-an-add form as the
 * accent rename above. `shadcn add` writes its own ring, radius, icon and
 * height ladders back into a regenerated file; these rules put them back onto
 * the hub tokens, so the two rendering paths land on the same pixels again
 * without anyone having to remember which class strings were edited.
 *
 * Per file rather than across the directory: `h-9` is a control height on a
 * button and a scroll frame on a menu, and only the components with an Astro
 * counterpart have been measured against one. Extend the file list when a
 * component joins the cohesion page. See AmbiqAI/helia-ui#20.
 */
const inReact = (rel, names) =>
  names.some((name) => rel === `${REACT_DIR}${name}`);

const ALIGNED = [
  'accordion.tsx',
  'badge.tsx',
  'button.tsx',
  'card.tsx',
  'input.tsx',
  'select.tsx',
  'tabs.tsx',
];

const ALIGN_RULES = [
  {
    name: 'shadcn-focus-ring',
    files: (rel) => inReact(rel, ALIGNED),
    pattern:
      /(?:focus-visible:border-ring )?focus-visible:ring-\[3px\] focus-visible:ring-ring\/50/g,
    replacement:
      'focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring',
  },
  {
    name: 'shadcn-icon-size',
    files: (rel) => inReact(rel, ALIGNED),
    pattern: /(\[&[>_]svg(?::not\(\[class\*='size-'\]\))?\]:)size-[34]\b/g,
    replacement: '$1size-[1em]',
  },
  {
    name: 'shadcn-transition',
    files: (rel) => inReact(rel, ALIGNED),
    pattern: /transition-(?:all|\[color,box-shadow\])/g,
    replacement: 'transition-colors',
  },
  {
    name: 'shadcn-pill',
    files: (rel) => inReact(rel, ['badge.tsx', 'button.tsx']),
    pattern: /rounded-(?:md|full)\b/g,
    replacement: 'rounded-pill',
  },
  {
    name: 'shadcn-control-height',
    files: (rel) => inReact(rel, ['button.tsx', 'input.tsx', 'select.tsx']),
    pattern: /\bh-(8|9|10)\b/g,
    replacement: (_, step) =>
      `min-h-(--helia-control-${{ 8: 'sm', 9: 'md', 10: 'lg' }[step]})`,
  },

  /*
   * The geometry and surface rules below are the second half of the same job:
   * where the ladders above put a regenerated file back on the hub's scales,
   * these put it back on the hub's grounds and insets. Each one replaces a
   * literal shadcn writes that only lands correctly on Tailwind's own scales
   * or on a page where preflight has run. See AmbiqAI/helia-ui#52.
   */

  /*
   * `w-6` reads the hub's `--spacing-6` (2rem), not Tailwind's 1.5rem, so the
   * small switch came out as wide as the default one and its thumb stopped
   * two thirds of the way along. Pinned to the value the travel assumes:
   * `translate-x-[calc(100%-2px)]` is track minus thumb minus both borders.
   */
  {
    name: 'shadcn-switch-track',
    files: (rel) => inReact(rel, ['switch.tsx']),
    pattern: /data-\[size=sm\]:w-6\b/g,
    replacement: 'data-[size=sm]:w-[1.5rem]',
  },

  /*
   * The unchecked control keeps a surface of its own rather than the UA button
   * face, and it is the same muted surface the slider track and the tab list
   * stand on.
   */
  {
    name: 'shadcn-unchecked-surface',
    files: (rel) => inReact(rel, ['checkbox.tsx', 'radio-group.tsx']),
    pattern: /dark:bg-input\/30 /g,
    replacement: 'bg-secondary ',
  },

  /*
   * A muted surface lightened by an alpha step hovers the wrong way on a light
   * theme. The hover surface is a token.
   */
  {
    name: 'shadcn-secondary-hover',
    files: (rel) => inReact(rel, ['button.tsx']),
    pattern: /hover:bg-secondary\/82/g,
    replacement: 'hover:bg-subtle hover:text-subtle-foreground',
  },

  /*
   * The overlay close buttons. shadcn insets them by a fixed `top-4 right-4`
   * that has nothing to do with the container's own padding, and dims them
   * with `opacity-70`, which is close enough to the disabled step to read as
   * one. The inset is a variable with the dialog's own padding as its
   * fallback, so one class string serves the dialog, the sheet and the palette
   * and only the two containers that differ declare anything: two competing
   * declarations of the same variable would be decided by their order in the
   * emitted stylesheet, which is not something a component can reason about.
   */
  {
    name: 'shadcn-overlay-close',
    files: (rel) => inReact(rel, ['dialog.tsx', 'sheet.tsx']),
    pattern:
      /absolute top-4 right-4 rounded-xs opacity-70 ring-offset-background transition-opacity hover:opacity-100 focus:ring-2 focus:ring-ring focus:ring-offset-2 focus:outline-hidden disabled:pointer-events-none(?: data-\[state=open\]:bg-(?:subtle|secondary))?(?: data-\[state=open\]:text-muted-foreground)?/g,
    replacement:
      'absolute top-[var(--helia-overlay-inset,var(--helia-space-6))] right-[var(--helia-overlay-inset,var(--helia-space-6))] inline-flex size-(--helia-control-sm) items-center justify-center rounded-pill text-muted-foreground transition-colors hover:bg-subtle hover:text-subtle-foreground focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring disabled:pointer-events-none',
  },
  {
    name: 'shadcn-overlay-inset',
    files: (rel) => inReact(rel, ['sheet.tsx']),
    pattern: /bg-background shadow-lg/g,
    replacement:
      'bg-background [--helia-overlay-inset:var(--helia-space-4)] shadow-lg',
  },

  /*
   * The palette has no content padding of its own, so its close button is
   * inset by the amount that centers an icon button on the search row, and the
   * row is a control height rather than a bare multiple.
   */
  {
    name: 'shadcn-command-row',
    files: (rel) => inReact(rel, ['command.tsx']),
    pattern:
      /'overflow-hidden p-0'|\*\*:data-\[slot=command-input-wrapper\]:h-12 |\[&_\[cmdk-input\]\]:h-12 |flex h-9 items-center gap-2 border-b px-3|'flex h-10 w-full rounded-md|size-4 shrink-0 opacity-50/g,
    replacement: (match) =>
      ({
        "'overflow-hidden p-0'":
          "'overflow-hidden p-0 [--helia-overlay-inset:calc((var(--helia-control-md)_-_var(--helia-control-sm))/2)]'",
        '**:data-[slot=command-input-wrapper]:h-12 ': '',
        '[&_[cmdk-input]]:h-12 ': '',
        'flex h-9 items-center gap-2 border-b px-3':
          'flex h-(--helia-control-md) items-center gap-2 border-b px-3',
        "'flex h-10 w-full rounded-md": "'flex h-full w-full rounded-md",
        'size-4 shrink-0 opacity-50': 'size-4 shrink-0 text-muted-foreground',
      })[match],
  },

  /*
   * Select drops below its trigger like every other menu. shadcn's default is
   * Radix's item-aligned position, which lifts the list over the heading above
   * the control, and its popper branch clamps the viewport to the trigger's
   * own height.
   */
  {
    name: 'shadcn-select-popper',
    files: (rel) => inReact(rel, ['select.tsx']),
    pattern:
      /position = 'item-aligned',(?:\n(\s*)align = 'center',)?|position=\{position\}\n(\s*)(?:align=\{align\}\n\s*)?\{\.\.\.props\}|'h-\[var\(--radix-select-trigger-height\)\] w-full/g,
    replacement: (match, declIndent, propIndent) => {
      if (match.startsWith('position =')) {
        const indent = declIndent ?? '  ';
        return `position = 'popper',\n${indent}align = 'start',\n${indent}sideOffset = 4,`;
      }
      if (match.startsWith('position={'))
        return `position={position}\n${propIndent}align={align}\n${propIndent}sideOffset={sideOffset}\n${propIndent}{...props}`;
      return "'w-full";
    },
  },

  /*
   * Both menu surfaces answer the pointer as well as the keyboard: Radix marks
   * the pointed-at row with `data-highlighted` and only moves DOM focus on
   * keyboard navigation.
   */
  {
    name: 'shadcn-highlighted-item',
    files: (rel) => inReact(rel, ['select.tsx', 'dropdown-menu.tsx']),
    pattern: /focus:bg-subtle focus:text-subtle-foreground(?! data-\[high)/g,
    replacement:
      'focus:bg-subtle focus:text-subtle-foreground data-[highlighted]:bg-subtle data-[highlighted]:text-subtle-foreground',
  },
];

function trackedFiles() {
  return execFileSync('git', ['ls-files'], { cwd: ROOT, encoding: 'utf8' })
    .split('\n')
    .filter(Boolean);
}

const counts = new Map();
let filesChanged = 0;

for (const rel of trackedFiles()) {
  if (SKIP_FILES.has(rel)) continue;
  if (!EXTENSIONS.has(path.extname(rel))) continue;

  const abs = path.join(ROOT, rel);
  const original = fs.readFileSync(abs, 'utf8');
  let next = original;

  const rules = [
    ...RULES,
    ...[ACCENT_RULE, ...ALIGN_RULES].filter((rule) => rule.files(rel)),
  ];
  for (const rule of rules) {
    const hits = next.match(rule.pattern);
    if (!hits) continue;
    counts.set(rule.name, (counts.get(rule.name) ?? 0) + hits.length);
    next = next.replace(rule.pattern, rule.replacement);
  }

  if (next === original) continue;
  filesChanged += 1;
  if (!dryRun) fs.writeFileSync(abs, next);
}

const total = [...counts.values()].reduce((sum, n) => sum + n, 0);
console.log(`rename-token-prefix: root ${ROOT}${dryRun ? ' (dry run)' : ''}`);
for (const [name, count] of counts) console.log(`  ${name}: ${count}`);
console.log(`  files changed: ${filesChanged}, replacements: ${total}`);
