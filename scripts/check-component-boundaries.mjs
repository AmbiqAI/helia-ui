/*
 * Enforces the component contract in docs/design-system-extraction-plan.md for
 * the components that ship in packages/helia-ui.
 *
 * Publishable is a matter of location now: every .astro file under the
 * package's astro/ directory is part of the published surface, so there is no
 * list here to fall out of step with the directory. A part takes its data
 * through props and children. It may build on another file in the package and
 * nothing else: not `src/data`, not a hub composition, which would drag the
 * hub's vocabulary along with it.
 *
 * Packages are denied by default rather than listed as exceptions, because the
 * imports that would quietly tie a component to this site -- Starlight's own
 * components, `astro:content` -- are exactly the ones nobody thinks to ban.
 *
 * Two directories are exceptions and have their own, wider allowlists.
 * starlight/ exists to plug into Starlight, so denying it Starlight would deny
 * it its purpose. react/ is generated by `shadcn add`, which writes whatever
 * the registry item was written against, so its allowlist is the package's own
 * manifest. Both are still fenced off from the hub.
 */

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

import {
  IGNORED_DIRS,
  PACKAGE_DIR,
  ROOT,
  WORKSPACE,
  isUnder,
  joinRel,
  pkg,
} from './lib/scope.mjs';

const PARTS_DIR = pkg('astro');
const PLUGIN_DIR = pkg('starlight');
const REACT_DIR = pkg('react');
/* The site the package must not reach into exists only in the workspace. */
const SITE_DIR = WORKSPACE ? 'src' : null;

const manifest = JSON.parse(
  fs.readFileSync(path.join(ROOT, PACKAGE_DIR, 'package.json'), 'utf8'),
);

/*
 * Matches `import ... from '<spec>'` and `export ... from '<spec>'`. The gap
 * excludes `;` rather than newlines, so a brace list wrapped over several lines
 * is still one statement.
 */
const FROM_SPECIFIER = /\b(?:import|export)\b[^;]*?\bfrom\s*['"]([^'"]+)['"]/g;
/* Matches a bare side-effect import, `import '<spec>'`. */
const BARE_SPECIFIER = /\bimport\s*['"]([^'"]+)['"]/g;
/* Matches a dynamic `import('<spec>')`. */
const DYNAMIC_SPECIFIER = /\bimport\s*\(\s*['"]([^'"]+)['"]/g;
/* Matches `import.meta.glob('<spec>')`, whose pattern is a specifier too. */
const GLOB_SPECIFIER = /\bimport\.meta\.glob\s*\(\s*['"]([^'"]+)['"]/g;
/* Matches a CSS `@import '<spec>'` or `@import url('<spec>')`. */
const CSS_IMPORT = /@import\s+(?:url\(\s*)?['"]([^'"]+)['"]/g;

/*
 * The packages a publishable component may reach for. `astro/types` and `shiki`
 * are types alone, so they leave nothing in the built output; `astro:components`
 * is Astro's own. FontAwesome is a real runtime dependency, and one the package
 * declares -- unlike `astro:content`, which would tie a component to a
 * particular site's collections and stays denied.
 *
 * `@astrojs/starlight/components` is the one Starlight entry a part may use. It
 * is a required peer dependency, so it ties a part to Starlight rather than to
 * a site, and `Code` is how a part renders through the same Expressive Code
 * instance the plugin themes instead of drawing a second code frame. Nothing
 * else under `@astrojs/starlight/` is open to this lane.
 */
const ALLOWED_PACKAGES = [
  'astro/types',
  'astro:components',
  'shiki',
  '@astrojs/starlight/components',
  '@fortawesome/fontawesome-svg-core',
  '@fortawesome/free-solid-svg-icons',
];

/*
 * The plugin lane is the one place in the package that is allowed to know
 * Starlight exists: it installs component overrides and reads the shell's
 * virtual modules, which is the whole point of the export. `astro` is here for
 * the integration type. The relaxation stops at this directory -- a part under
 * astro/ that reached for Starlight would still be tying itself to one site.
 */
const PLUGIN_ALLOWED_PACKAGES = [...ALLOWED_PACKAGES, 'astro'];
const PLUGIN_ALLOWED_PREFIXES = [
  '@astrojs/starlight/',
  'virtual:starlight/',
  'virtual:helia-ui/',
];

/*
 * The React lane is allowed exactly what the package declares it needs, read
 * from the manifest rather than restated here: shadcn's generated files import
 * whatever the registry item was written against, so the list that has to stay
 * true is the one npm installs. An import the manifest does not cover is a
 * missing dependency in a package that ships source, which is a failure a
 * consuming site would hit and this repo would not.
 */
const REACT_ALLOWED_PACKAGES = [
  ...Object.keys(manifest.dependencies ?? {}),
  ...Object.keys(manifest.peerDependencies ?? {}),
];
/* Subpath entries of those same packages, `react/jsx-runtime` being the one
 * the JSX transform can emit on its own. */
const REACT_ALLOWED_PREFIXES = REACT_ALLOWED_PACKAGES.map((name) => `${name}/`);

const failures = [];

function lineOf(source, index) {
  return source.slice(0, index).split('\n').length;
}

function specifiers(source, patterns) {
  const found = [];
  for (const pattern of patterns) {
    pattern.lastIndex = 0;
    let match;
    while ((match = pattern.exec(source)) !== null) {
      found.push({ specifier: match[1], line: lineOf(source, match.index) });
    }
  }
  return found;
}

function relativeTo(rel, specifier) {
  return path
    .relative(ROOT, path.resolve(path.dirname(path.join(ROOT, rel)), specifier))
    .split(path.sep)
    .join('/');
}

function packageFiles(dir) {
  const files = [];
  for (const entry of fs
    .readdirSync(path.join(ROOT, dir), { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = joinRel(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name)) continue;
      files.push(...packageFiles(rel));
    } else if (/\.(astro|css|tsx?)$/.test(entry.name)) files.push(rel);
  }
  return files;
}

/** Scans one directory of the package against its own import allowlist. */
function checkScope({ dir, extensions, packages, prefixes = [] }) {
  const names = fs
    .readdirSync(path.join(ROOT, dir))
    .filter((name) => extensions.some((ext) => name.endsWith(ext)))
    .sort();

  if (names.length === 0) {
    failures.push(`${dir} holds no files; the package is the source`);
  }

  for (const name of names) {
    const rel = `${dir}/${name}`;
    const source = fs.readFileSync(path.join(ROOT, rel), 'utf8');

    for (const { specifier, line } of specifiers(source, [
      FROM_SPECIFIER,
      BARE_SPECIFIER,
      DYNAMIC_SPECIFIER,
      GLOB_SPECIFIER,
    ])) {
      if (!specifier.startsWith('.')) {
        const allowed =
          packages.includes(specifier) ||
          prefixes.some((prefix) => specifier.startsWith(prefix));
        if (!allowed) {
          failures.push(
            `${rel}:${line} package: imports ${specifier}; files in ${dir} may only import ${[...packages, ...prefixes.map((prefix) => `${prefix}*`)].join(', ')}`,
          );
        }
        continue;
      }

      const target = relativeTo(rel, specifier);

      if (SITE_DIR && isUnder(target, `${SITE_DIR}/data`)) {
        failures.push(
          `${rel}:${line} data: imports ${specifier}; publishable components take data through props`,
        );
        continue;
      }

      if (!isUnder(target, PACKAGE_DIR)) {
        failures.push(
          `${rel}:${line} escape: imports ${specifier}, which resolves to ${target}, outside the package`,
        );
      }
    }
  }

  return names.length;
}

const partCount = checkScope({
  dir: PARTS_DIR,
  extensions: ['.astro'],
  packages: ALLOWED_PACKAGES,
});

const pluginCount = checkScope({
  dir: PLUGIN_DIR,
  extensions: ['.astro', '.ts'],
  packages: PLUGIN_ALLOWED_PACKAGES,
  prefixes: PLUGIN_ALLOWED_PREFIXES,
});

const reactCount = checkScope({
  dir: REACT_DIR,
  extensions: ['.tsx', '.ts'],
  packages: REACT_ALLOWED_PACKAGES,
  prefixes: REACT_ALLOWED_PREFIXES,
});

/*
 * The same rule read from the other end. A relative path that climbs out of the
 * package is caught above for .astro; this catches the package's stylesheets
 * too, and reports a reach into the site by name rather than as an escape,
 * because that is the failure that actually happens.
 */
for (const rel of packageFiles(PACKAGE_DIR)) {
  const source = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const patterns = rel.endsWith('.css')
    ? [CSS_IMPORT]
    : [FROM_SPECIFIER, BARE_SPECIFIER, DYNAMIC_SPECIFIER, GLOB_SPECIFIER];
  for (const { specifier, line } of specifiers(source, patterns)) {
    if (!specifier.startsWith('.')) continue;
    const target = relativeTo(rel, specifier);
    if (SITE_DIR && isUnder(target, SITE_DIR)) {
      failures.push(
        `${rel}:${line} site: imports ${specifier}, which resolves to ${target}; the package may not depend on the hub`,
      );
    }
  }
}

if (failures.length > 0) {
  for (const failure of failures) console.error(failure);
  console.error(
    `\n${failures.length} boundary violation${failures.length === 1 ? '' : 's'}. See docs/design-system.md, "Composable components".`,
  );
  process.exit(1);
}

console.log(
  `check:boundaries: ${partCount} publishable components in ${PARTS_DIR}, ${pluginCount} plugin files in ${PLUGIN_DIR}, ${reactCount} React components in ${REACT_DIR}, no violations.`,
);
